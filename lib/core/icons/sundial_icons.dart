  static IconData resolve(String name, {IconData fallback = Icons.folder_outlined}) => all[name] ?? fallback;

  static List<String> search(String query) {
    final normalized = query.trim().toLowerCase().replaceAll('_', ' ');
    if (normalized.isEmpty) return names;
    final tokens = normalized.split(RegExp(r'\s+'));
    return [
      for (final name in all.keys)
        if (tokens.every((token) => _searchable(name).contains(token))) name,
    ];
  }

  static String _searchable(String key) {
    final readable = key.replaceAll('_', ' ');
    final synonyms = _synonyms[key];
    return synonyms == null ? readable : '$readable ${synonyms.join(' ')}';
  }

